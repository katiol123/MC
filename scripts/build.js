// Bundles src/ (ES modules) into one classic script, boneforge.bundle.js, so index.html also works
// when opened straight from disk (file://), where browsers refuse to load ES modules.
// Zero dependencies: supports exactly the module syntax this project uses
// (`import { a, b as c } from './x.js'`, `import * as K from`, `export function|class|const|let`).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = 'src/main.js';
const modules = new Map();

function load(rel) {
  if (modules.has(rel)) return;
  modules.set(rel, null);
  let code = fs.readFileSync(path.join(root, rel), 'utf8');
  const deps = [];
  const resolve = (spec) => path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec));
  code = code.replace(/^import\s+\{([^}]*)\}\s+from\s+'([^']+)';?/gm, (_, names, spec) => {
    const dep = resolve(spec);
    deps.push(dep);
    const binds = names.split(',').map((s) => s.trim()).filter(Boolean)
      .map((s) => s.replace(/^(\w+)\s+as\s+(\w+)$/, '$1: $2')).join(', ');
    return `const { ${binds} } = __require(${JSON.stringify(dep)});`;
  });
  code = code.replace(/^import\s+\*\s+as\s+(\w+)\s+from\s+'([^']+)';?/gm, (_, name, spec) => {
    const dep = resolve(spec);
    deps.push(dep);
    return `const ${name} = __require(${JSON.stringify(dep)});`;
  });
  if (/^\s*import\s/m.test(code)) throw new Error(`${rel}: unsupported import syntax`);
  const exported = [];
  code = code.replace(/^export\s+(async\s+function|function|class|const|let)\s+(\w+)/gm, (_, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*export\s/m.test(code)) throw new Error(`${rel}: unsupported export syntax`);
  const getters = exported.map((n) => `  Object.defineProperty(__exports, ${JSON.stringify(n)}, { enumerable: true, get: () => ${n} });`).join('\n');
  modules.set(rel, `__define(${JSON.stringify(rel)}, function (__exports, __require) {\n${getters}\n${code}\n});`);
  deps.forEach(load);
}

load(entry);
const out = `// GENERATED by scripts/build.js from src/ — do not edit by hand (run: npm run build)
(function () {
  'use strict';
  const __defs = {}, __cache = {};
  function __define(id, fn) { __defs[id] = fn; }
  function __require(id) {
    if (__cache[id]) return __cache[id];
    const exp = (__cache[id] = {});
    __defs[id](exp, __require);
    return exp;
  }
${[...modules.values()].join('\n')}
  __require(${JSON.stringify(entry)});
})();
`;
const target = path.join(root, 'boneforge.bundle.js');
if (process.argv.includes('--check')) {
  // used by `npm test`: fail if someone changed src/ without rebuilding the bundle
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('boneforge.bundle.js is out of date: run `npm run build`');
    process.exit(1);
  }
  console.log('bundle up to date');
  process.exit(0);
}
fs.writeFileSync(target, out);
console.log(`bundled ${modules.size} modules -> boneforge.bundle.js (${(out.length / 1024).toFixed(0)} KB)`);
